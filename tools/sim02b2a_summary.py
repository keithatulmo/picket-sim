"""Markdown summary tables for the SIM-02B.2-A report, read only from a run's tables.

    python tools/sim02b2a_summary.py results/sim02b2a/<run_id> > reports/SIM-02B2A_summary_tables.md

Every number the engineering report quotes comes from these tables or from the run tables directly, and is
rechecked by tools/check_sim02b2a_claims.py.
"""

from __future__ import annotations

import csv
import gzip
import json
import math
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from picket_sim.detection import calibration_pvalue  # noqa: E402

FLAG_P = 1e-3  # a realized count is flagged when its exact predictive tail probability is below this

CANDS = ("A0", "A1", "P8-C", "A4")
ARRAYS = ("A1", "P8-C", "A4")
ADAPT = ("TREF-CA16", "TREF-OS16", "FREF-CA8", "FREF-OS8")
NORMS = ("ORACLE", "NOMINAL") + ADAPT
SCEN_C1 = ("STAT", "SHAPE-HI", "SHAPE-LO", "STEP+1", "STEP+3", "INTERF", "COH")
CLASSES = ("tone", "harmonic", "broadband", "chirp")
DET = {"tone": "tonal", "harmonic": "harmonic", "broadband": "energy", "chirp": "mf"}


def load(run: Path, name: str) -> list[dict]:
    p = run / "tables" / name
    if name.endswith(".gz"):
        with gzip.open(p, "rt") as fh:
            return list(csv.DictReader(fh))
    return list(csv.DictReader(open(p)))


def f(x) -> float:
    try:
        return float(x)
    except (TypeError, ValueError):
        return float("nan")


def one(rows, **k):
    out = [r for r in rows if all((f(r[a]) == v) if isinstance(v, float) else (r[a] == v) for a, v in k.items())]
    if len(out) > 1:
        raise KeyError((k, len(out)))
    return out[0] if out else None


def modes(c):
    return ("single",) if c == "A0" else ("beam_search", "incoherent")


def tails(r, thr):
    """Exact predictive tail probabilities (upper, lower) of a realized count under correct calibration of the
    design threshold: binomial for exact, quadratic-form and conditional Monte Carlo thresholds; beta-binomial for
    empirical and fast-simulation thresholds (calibration_pvalue, as in the run self-check)."""
    t = thr.get((r["candidate"], r["cell"], r["normalizer"], r["mode"], r["detector"], r["pfa_target"]))
    meth = "empirical" if t["method"] in ("empirical", "fast null simulation") else "exact"
    k, n, p = int(r["realized_k"]), int(r["n_eval"]), f(r["pfa_target"])
    _, up = calibration_pvalue(meth, k, n, p, int(t["n"]) if meth == "empirical" else 0)
    # lower tail: P(K <= k) = 1 - P(K >= k + 1)
    lo = 1.0 - calibration_pvalue(meth, k + 1, n, p, int(t["n"]) if meth == "empirical" else 0)[1] if k < n else 1.0
    return up, lo


def flag(up, lo):
    return " L" if up < FLAG_P else " C" if lo < FLAG_P else ""


def pfa_cell(r, target, fl):
    """Realized Pfa in units of the target with its Wilson interval, and the exact-test mark."""
    if r is None:
        return ""
    return (f"{f(r['realized_pfa']) / target:.2f} [{f(r['realized_lo']) / target:.2f}, "
            f"{f(r['realized_hi']) / target:.2f}]{fl.get(id(r), '')}")


def loss_cell(r, mark=""):
    if r is None:
        return ""
    v = f(r["loss_db"])
    if not math.isfinite(v):
        return "cens." + mark
    return f"{v:+.2f}{mark}"


def main(run_dir: str) -> int:
    run = Path(run_dir)
    rec = json.loads((run / "record.json").read_text())
    thr = load(run, "thresholds.csv")
    pfa = load(run, "realized_pfa.csv")
    err = load(run, "estimation_error.csv")
    snr = load(run, "snr_required.csv")
    loss = load(run, "detection_loss_vs_oracle.csv")
    gain = load(run, "gain_vs_a0.csv")
    cfar = load(run, "cfar_loss_exact.csv")
    cost = load(run, "normalizer_cost.csv")
    T = rec["timings_s"]
    tix = {(r["candidate"], r["cell"], r["normalizer"], r["mode"], r["detector"], r["pfa_target"]): r for r in thr}
    TAIL, FL = {}, {}
    for r in pfa:
        up, lo = tails(r, tix)
        TAIL[id(r)] = (up, lo)
        FL[id(r)] = flag(up, lo)
    alias = {"TREF-CA16-G8": "TREF-CA16"}
    pix = {(r["candidate"], r["cell"], r["scenario"], r["normalizer"], r["mode"], r["detector"], r["pfa_target"]): r
           for r in pfa}

    def lmark(r):
        """Exact-test false-alarm mark of the normalizer behind a loss row (CONTAM uses the STAT null)."""
        if r is None:
            return ""
        sc = "STAT" if r["scenario"] == "CONTAM" else r["scenario"]
        q = pix.get((r["candidate"], r["cell"], sc, alias.get(r["normalizer"], r["normalizer"]), r["mode"],
                     DET[r["class"]], r["pfa_target"]))
        return FL.get(id(q), "") if q else ""
    O = [f"# SIM-02B.2-A summary tables (run `{run.name}`)", "",
         "Generated by `tools/sim02b2a_summary.py` from the run tables. Pfa is per decision window; false alerts per "
         "hour = Pfa x 3600 / T for one detector on non-overlapping windows. Marks: L (C) = realized count above (below) "
         "what a correctly calibrated design threshold produces, exact predictive tail probability below 0.001 "
         "(binomial for exact, quadratic-form and conditional Monte Carlo thresholds; beta-binomial for empirical and "
         "fast-simulation thresholds, which accounts for the threshold's own sampling error). Losses are SNR required with the "
         "normalizer minus SNR required with ORACLE (same candidate, mode, class, scenario, trials); 'cens.' = Pd "
         "target not reached on the SNR grid by one of the two.", "",
         f"Run: code `{rec['software']['git_commit'][:7]}` (dirty: {rec['software']['git_dirty']}), workers "
         f"{rec['workers']}, calibration {T['calibration_s']:.0f} s, evaluation {T['evaluation_s']:.0f} s, total "
         f"{T['total_s']:.0f} s.", "", "Self-checks: " + "; ".join(f"`{k}` = {v}" for k, v in rec["self_checks"].items()),
         ""]

    # ---- S1 threshold methods
    O += ["## S1. Threshold methods", "", "| Method | Rows | Pfa 1e-2 | Pfa 1e-3 | Pfa 1e-4 |", "|---|---|---|---|---|"]
    for m in sorted({r["method"] for r in thr}):
        rs = [r for r in thr if r["method"] == m]
        O.append(f"| {m} | {len(rs)} | " + " | ".join(str(sum(1 for r in rs if f(r['pfa_target']) == p))
                                                      for p in (0.01, 0.001, 0.0001)) + " |")
    O += ["", "Sequential array calibration (nominal design):", "",
          "| Candidate | Cell | Trials | Stop | Adaptive threshold interval at Pfa 1e-3, median and max (dB) |",
          "|---|---|---|---|---|"]
    for c in ARRAYS:
        for cell in ("C1", "C2", "C3"):
            rs = [r for r in thr if r["candidate"] == c and r["cell"] == cell]
            if not rs:
                continue
            w = sorted(f(r["eta_interval_db"]) for r in rs if r["normalizer"] in ADAPT and f(r["pfa_target"]) == 1e-3
                       and math.isfinite(f(r["eta_interval_db"])))
            O.append(f"| {c} | {cell} | {rs[0]['n_sequential']} | {rs[0]['stop']} | "
                     + (f"{w[len(w) // 2]:.2f}, {w[-1]:.2f} |" if w else "n/a |"))
    agree = [r for r in thr if r.get("empirical_eta") not in (None, "") and r["normalizer"] == "ORACLE"]
    if agree:
        O += ["", "ORACLE exact or conditional Monte Carlo thresholds against the sequential empirical threshold of the "
              "same statistic (Pfa where n p >= 10). NOMINAL rows are the same statistics under the nominal design and "
              "are not counted twice.", "",
              "| Method | Statistics | Inside empirical 95 % interval | Max abs difference (dB) |", "|---|---|---|---|"]
        for m in sorted({r["method"] for r in agree}):
            rs = [r for r in agree if r["method"] == m]
            ins = sum(1 for r in rs if f(r["empirical_eta_lo"]) <= f(r["eta"]) <= f(r["empirical_eta_hi"]))
            d = max(abs(10 * math.log10(f(r["eta"]) / f(r["empirical_eta"]))) for r in rs)
            O.append(f"| {m} | {len(rs)} | {ins} | {d:.3f} |")

    # ---- S2 STAT calibration
    O += ["", "## S2. False-alarm calibration under the nominal design (STAT, all cells)", "",
          "Exact predictive test of each realized count (rows with n Pfa >= 1, as the run self-check). Under correct "
          "calibration the two-sided p-values are uniform, so about 5 % fall below 0.05.", "",
          "| Normalizer | Rows | Two-sided p < 0.05 | Flagged L (upper tail < 0.001) | Flagged C (lower tail < 0.001) "
          "| Smallest upper-tail p |", "|---|---|---|---|---|---|"]
    st = [r for r in pfa if r["scenario"] == "STAT" and int(r["n_eval"]) * f(r["pfa_target"]) >= 1]

    def s2row(name, rs):
        tl = [TAIL[id(r)] for r in rs]
        p2 = [min(1.0, 2 * min(u, lo)) for u, lo in tl]
        return (f"| {name} | {len(rs)} | {sum(1 for x in p2 if x < 0.05)} ({100 * sum(1 for x in p2 if x < 0.05) / len(rs):.1f} %) "
                f"| {sum(1 for u, _ in tl if u < FLAG_P)} | {sum(1 for _, lo in tl if lo < FLAG_P)} | "
                f"{min(u for u, _ in tl):.2g} |")
    for n in sorted({r["normalizer"] for r in st}, key=lambda x: (x not in NORMS, x)):
        O.append(s2row(n, [r for r in st if r["normalizer"] == n]))
    O.append(s2row("all", st))

    # ---- S3 false-alarm robustness
    for p0 in (1e-3, 1e-2):
        O += ["", f"## S3{'a' if p0 == 1e-3 else 'b'}. Realized Pfa / target by scenario, C1 (B2, 1 s), target {p0:g}", "",
              "Each cell: realized / target [Wilson 95 %]. Thresholds from the nominal design.", ""]
        cols = [("A0", "single", "tonal"), ("A0", "single", "energy"), ("P8-C", "beam_search", "tonal"),
                ("P8-C", "beam_search", "energy"), ("P8-C", "incoherent", "tonal"), ("A1", "beam_search", "tonal"),
                ("A4", "beam_search", "tonal")]
        O += ["| Scenario | Normalizer | " + " | ".join(f"{c} {m} {d}" for c, m, d in cols) + " |",
              "|---|---|" + "---|" * len(cols)]
        for sc in SCEN_C1:
            for n in NORMS:
                cells = [pfa_cell(one(pfa, candidate=c, cell="C1", scenario=sc, normalizer=n, mode=m, detector=d,
                                      pfa_target=p0), p0, FL) for c, m, d in cols]
                O.append(f"| {sc} | {n} | " + " | ".join(cells) + " |")

    # ---- S4 loss vs ORACLE, STAT
    for cell in ("C1", "C2", "C3"):
        for pd in (0.5, 0.9):
            O += ["", f"## S4 {cell}. Detection loss against ORACLE (dB), STAT, Pfa 1e-3, Pd {pd}", "",
                  "| Candidate | Mode | Class | " + " | ".join(n for n in NORMS if n != "ORACLE") + " |",
                  "|---|---|---|" + "---|" * (len(NORMS) - 1)]
            for c in CANDS:
                for m in modes(c):
                    for cl in CLASSES:
                        rr = [one(loss, candidate=c, cell=cell, scenario="STAT", **{"class": cl}, normalizer=n, mode=m,
                                  pfa_target=1e-3, pd_target=pd) for n in NORMS if n != "ORACLE"]
                        cells = [loss_cell(x, lmark(x)) for x in rr]
                        if any(cells):
                            O.append(f"| {c} | {m} | {cl} | " + " | ".join(cells) + " |")

    # ---- S5 loss in other scenarios, C1
    for cl in ("tone", "broadband"):
        O += ["", f"## S5 {cl}. Detection loss against ORACLE (dB) by scenario, C1, Pfa 1e-3, Pd 0.5", "",
              "A loss next to L was obtained at a liberal realized Pfa and is not a detection result.", "",
              "| Scenario | Candidate | Mode | " + " | ".join(n for n in NORMS if n != "ORACLE") + " |",
              "|---|---|---|" + "---|" * (len(NORMS) - 1)]
        for sc in SCEN_C1:
            for c in CANDS:
                for m in modes(c):
                    rr = [one(loss, candidate=c, cell="C1", scenario=sc, **{"class": cl}, normalizer=n, mode=m,
                              pfa_target=1e-3, pd_target=0.5) for n in NORMS if n != "ORACLE"]
                    cells = [loss_cell(x, lmark(x)) for x in rr]
                    if any(cells):
                        O.append(f"| {sc} | {c} | {m} | " + " | ".join(cells) + " |")

    # ---- S6 contamination
    cn = ("ORACLE", "TREF-CA16", "TREF-CA16-G8", "TREF-OS16", "FREF-CA8", "FREF-OS8")
    O += ["", "## S6. Target contamination of reference windows (CONTAM, C1, Pfa 1e-3, Pd 0.5)", "",
          "SNR required (dB) with the STAT value of the same normalizer in parentheses; 'cens.' = Pd 0.5 not reached.",
          "", "| Class | Candidate | Mode | " + " | ".join(cn) + " |", "|---|---|---|" + "---|" * len(cn)]

    def sv(r):
        if r is None:
            return ""
        v = f(r["snr_req_db"])
        return f"{v:.1f}" if math.isfinite(v) else "cens."
    for cl in ("tone", "broadband"):
        for c in CANDS:
            for m in modes(c):
                cells = []
                for n in cn:
                    a = one(snr, candidate=c, cell="C1", scenario="CONTAM", **{"class": cl}, normalizer=n, mode=m,
                            pfa_target=1e-3, pd_target=0.5)
                    b = one(snr, candidate=c, cell="C1", scenario="STAT", **{"class": cl},
                            normalizer=("TREF-CA16" if n == "TREF-CA16-G8" else n), mode=m, pfa_target=1e-3,
                            pd_target=0.5)
                    cells.append(f"{sv(a)} ({sv(b)})" if a else "")
                O.append(f"| {cl} | {c} | {m} | " + " | ".join(cells) + " |")

    # ---- S7 estimation error
    O += ["", "## S7. Background estimation error, C1 (estimate / true test-window background, dB)", "",
          "| Scenario | Candidate | Mode | Normalizer | Bias | Std | 5 % | 95 % |", "|---|---|---|---|---|---|---|---|"]
    for sc in SCEN_C1:
        for c, m in (("A0", "single"), ("P8-C", "beam_search")):
            for n in ADAPT:
                r = one(err, candidate=c, cell="C1", scenario=sc, normalizer=n, mode=m)
                if r:
                    O.append(f"| {sc} | {c} | {m} | {n} | {f(r['bias_db']):+.2f} | {f(r['std_db']):.2f} | "
                             f"{f(r['p05_db']):+.2f} | {f(r['p95_db']):+.2f} |")

    # ---- S8 A0 CFAR loss against M
    O += ["", "## S8. A0 tonal CFAR loss against reference count M, STAT, Pfa 1e-3", "",
          "| Cell | M | Exact (large-SNR threshold ratio, dB) | Measured, tone, Pd 0.5 (dB) | Measured, tone, Pd 0.9 (dB) |",
          "|---|---|---|---|---|"]
    for cell in ("C1", "C2", "C3"):
        for r in [x for x in cfar if x["cell"] == cell and f(x["pfa_target"]) == 1e-3]:
            M = int(r["M"])
            nid = "TREF-CA16" if M == 16 else f"TREF-CA{M}-A0"
            ms = [one(loss, candidate="A0", cell=cell, scenario="STAT", **{"class": "tone"}, normalizer=nid,
                      mode="single", pfa_target=1e-3, pd_target=pd) for pd in (0.5, 0.9)]
            O.append(f"| {cell} | {M} | {f(r['tonal_cfar_loss_db']):.2f} | "
                     + " | ".join(loss_cell(x, lmark(x)) for x in ms) + " |")

    # ---- S9 gain vs A0
    O += ["", "## S9. Gain over A0 with the same normalizer (dB), STAT, Pfa 1e-3, Pd 0.5", "",
          "| Cell | Class | Candidate | Mode | " + " | ".join(NORMS) + " |", "|---|---|---|---|" + "---|" * len(NORMS)]
    for cell in ("C1", "C2", "C3"):
        for cl in CLASSES:
            for c in ARRAYS:
                for m in modes(c):
                    cells = []
                    for n in NORMS:
                        r = one(gain, candidate=c, cell=cell, scenario="STAT", **{"class": cl}, normalizer=n, mode=m,
                                pfa_target=1e-3, pd_target=0.5)
                        v = f(r["gain_db"]) if r else float("nan")
                        cells.append("" if r is None else (f"{v:+.2f}" if math.isfinite(v) else "cens."))
                    if any(cells):
                        O.append(f"| {cell} | {cl} | {c} | {m} | " + " | ".join(cells) + " |")

    # ---- S10 cost and per-hour conversion
    O += ["", "## S10. Normalizer processing cost (this machine, indicative)", "",
          "| Normalizer | ns per stream-bin | Operations per stream-bin | Windows held |", "|---|---|---|---|"]
    O += [f"| {r['normalizer']} | {f(r['ns_per_stream_bin']):.2f} | {r['operations_per_stream_bin']} | "
          f"{r['memory_windows']} |" for r in cost]
    O += ["", "## S11. False alerts per hour per detector (non-overlapping windows)", "",
          "| Window (s) | Pfa 1e-2 | Pfa 1e-3 | Pfa 1e-4 |", "|---|---|---|---|"]
    for w in (0.1, 1.0):
        O.append(f"| {w:g} | " + " | ".join(f"{p * 3600 / w:g}" for p in (0.01, 0.001, 0.0001)) + " |")
    print("\n".join(O))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
