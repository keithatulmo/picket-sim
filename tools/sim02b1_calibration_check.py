"""Exact false-alarm calibration test for a SIM-02B.1 run (reads the run tables only).

The run self-check compares realized Pfa with a Wilson interval that covers only the evaluation set. For an
empirical threshold that is itself an order statistic of the calibration set, the exact predictive law of the
evaluation exceedance count K_e, for exchangeable continuous statistics, is beta-binomial:

    threshold = m-th order statistic of n_c calibration values (k_c = n_c - m values above it)
    K_e ~ BetaBinomial(n_e, alpha = k_c + 1, beta = n_c - k_c)

For exact thresholds (and union bounds that coincide with exact laws) K_e ~ Binomial(n_e, Pfa); a conservative
bound gives K_e stochastically smaller. This tool computes two-sided (empirical, exact) and upper-tail (bound)
p-values per row, and reports their distribution. Under correct calibration, two-sided p-values are close to
uniform (about 5 % below 0.05), and the smallest p-value times the number of rows (Bonferroni) is not small.
Rows that share a noise set (modes and detectors of one case) are correlated, so the Bonferroni figure is
conservative.

    python tools/sim02b1_calibration_check.py results/sim02b1/<run_id> > reports/SIM-02B1_calibration_check.md
"""

from __future__ import annotations

import csv
import math
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from picket_sim.detection import calibration_pvalue  # noqa: E402


def main(run_dir: str) -> int:
    run = Path(run_dir)
    rows = [r for r in csv.DictReader(open(run / "tables" / "thresholds_and_pfa.csv")) if r["kind"] == "primary"]
    res = {"empirical": [], "exact": [], "bound": []}
    for r in rows:
        p, n_e, n_c = float(r["pfa_target"]), int(r["n_eval"]), int(r["n_cal"])
        if r["method"] in ("empirical", "exact"):
            two, up = calibration_pvalue(r["method"], int(r["realized_k"]), n_e, p, n_c)
            res[r["method"]].append((two, up, r))
        bd = float(r["bound_eta"])
        if math.isfinite(bd) and math.isfinite(float(r["bound_realized_pfa"])):
            k = int(round(float(r["bound_realized_pfa"]) * n_e))
            _, up = calibration_pvalue("bound", k, n_e, p)
            res["bound"].append((up, up, r))

    out = [f"# SIM-02B.1 false-alarm calibration check (run `{run.name}`)", "",
           "Generated by `tools/sim02b1_calibration_check.py` from `tables/thresholds_and_pfa.csv` (matched-noise "
           "rows). p-values: empirical thresholds against the exact beta-binomial predictive law; exact thresholds "
           "against the binomial law; union-bound thresholds one-sided (upper tail) against the binomial law at the "
           "target, which is conservative for a valid bound.", "",
           "| Threshold method | Rows | Fraction of p-values below 0.05 | Fraction below 0.01 | Smallest p-value | "
           "Smallest p-value x rows |", "|---|---|---|---|---|---|"]
    for meth in ("exact", "empirical", "bound"):
        v = res[meth]
        if not v:
            continue
        ps = np.array([x[0] for x in v])
        out.append(f"| {meth} | {len(v)} | {np.mean(ps < 0.05):.3f} | {np.mean(ps < 0.01):.3f} | {ps.min():.2e} | "
                   f"{min(1.0, ps.min() * len(v)):.3f} |")
    out += ["", "Rows with the smallest p-values:", "",
            "| Method | Candidate | Band | Window (s) | Scenario | Mode | Detector | Target | Calibration / evaluation trials | "
            "Realized | p-value |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    allv = sorted([(x[0], meth, x[2]) for meth, v in res.items() for x in v], key=lambda t: t[0])[:8]
    for pv, meth, r in allv:
        real = r["realized_pfa"] if meth != "bound" else r["bound_realized_pfa"]
        out.append(f"| {meth} | {r['candidate']} | {r['band']} | {float(r['window_s']):g} | {r['truth']} | {r['mode']} | "
                   f"{r['detector']} | {float(r['pfa_target']):g} | {r['n_cal']} / {r['n_eval']} | {float(real):.4f} | "
                   f"{pv:.2e} |")
    out.append("")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1]))
