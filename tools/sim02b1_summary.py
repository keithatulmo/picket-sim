"""Markdown summary tables for the SIM-02B.1 report, read only from a run's tables.

    python tools/sim02b1_summary.py results/sim02b1/<run_id> > reports/SIM-02B1_summary_tables.md

Every number the engineering report quotes comes from these tables or from the run tables directly, and is
rechecked by tools/check_sim02b1_claims.py.
"""

from __future__ import annotations

import csv
import math
import sys
from collections import defaultdict
from pathlib import Path

CLASSES = ("tone", "harmonic", "broadband", "chirp")
MODES = ("beam_known", "beam_search", "incoherent")


def load(run: Path, name: str) -> list[dict]:
    return list(csv.DictReader(open(run / "tables" / name)))


def f(x) -> float:
    try:
        return float(x)
    except (TypeError, ValueError):
        return float("nan")


def cell(g: dict | None) -> str:
    if g is None:
        return ""
    v = f(g["gain_db"])
    if not math.isfinite(v):
        return "cens."
    ok = ("exact", "empirical")
    flag = "" if g["threshold_method"] in ok and g["a0_threshold_method"] in ok else "*"
    return f"{v:+.1f} [{f(g['gain_lo_db']):+.1f}, {f(g['gain_hi_db']):+.1f}]{flag}"


def gain_index(gain):
    idx = {}
    for r in gain:
        idx[(r["scenario"], r["candidate"], r["mode"], r["band"], f(r["window_s"]), r["class"], f(r["pfa_target"]),
             f(r["pd_target"]))] = r
    return idx


def main(run_dir: str) -> int:
    run = Path(run_dir)
    gain = load(run, "detection_gain_vs_a0.csv")
    thr = load(run, "thresholds_and_pfa.csv")
    snr = load(run, "snr_required.csv")
    gi = gain_index(gain)
    cands_p = [c for c in ("A1", "A2", "P6-C", "P8-C", "A4")]
    cands_s = [c for c in ("P8-E", "SQ4-C", "V-C", "V-D", "V-DS")]
    out = [f"# SIM-02B.1 summary tables (run `{run.name}`)", "",
           "Generated by `tools/sim02b1_summary.py` from the run tables. Gains are SNR_req(A0) - SNR_req(candidate)"
           " in dB at Pd = 0.5 and Pfa = 1e-3 with 95 % intervals; positive means the candidate needs less input SNR"
           " than A0. `*` marks a threshold set by a union bound (conservative); `cens.` means the SNR required lies"
           " outside the simulated grid for A0 or the candidate.", ""]

    # A0 operating points
    out += ["## A0 input SNR required (Pd = 0.5, Pfa = 1e-3), ambient-limited (N-AMB)", "",
            "| Class | Units | " + " | ".join(f"{b} {w:g} s" for b in ("B1", "B2", "B3") for w in (0.1, 1, 10)) + " |",
            "|---|---|" + "---|" * 9]
    units = {"tone": "dB re 1 Hz", "harmonic": "dB re 1 Hz per harmonic", "broadband": "dB in band",
             "chirp": "E/N0_eff dB"}
    for cls in CLASSES:
        cells = []
        for b in ("B1", "B2", "B3"):
            for w in (0.1, 1.0, 10.0):
                r = [x for x in snr if x["candidate"] == "A0" and x["scenario"] == "N-AMB" and x["band"] == b
                     and f(x["window_s"]) == w and x["class"] == cls and f(x["pfa_target"]) == 1e-3
                     and f(x["pd_target"]) == 0.5]
                cells.append(f"{f(r[0]['snr_req_db']):.1f}" if r and r[0]["status"] == "ok" else
                             (r[0]["status"] if r else ""))
        out.append(f"| {cls} | {units[cls]} | " + " | ".join(cells) + " |")
    out.append("")

    for mode in MODES:
        out += [f"## Gain over A0, {mode}, ambient-limited (N-AMB), primary candidates", ""]
        for cls in CLASSES:
            cols = [(b, w) for b in ("B1", "B2", "B3") for w in (0.1, 1.0, 10.0)]
            out += [f"**{cls}**", "", "| Candidate | " + " | ".join(f"{b} {w:g} s" for b, w in cols) + " |",
                    "|---|" + "---|" * len(cols)]
            for c in cands_p:
                out.append(f"| {c} | " + " | ".join(cell(gi.get(("N-AMB", c, mode, b, w, cls, 1e-3, 0.5)))
                                                    for b, w in cols) + " |")
            out.append("")

    out += ["## Gain over A0 by noise scenario, T = 1 s, beam_search and incoherent", ""]
    for cls in CLASSES:
        out += [f"**{cls}**", "", "| Candidate | Mode | " + " | ".join(f"{sc} {b}" for sc in ("N-AMB", "N-FLOW", "N-SENS")
                                                                  for b in ("B1", "B2", "B3")) + " |",
                "|---|---|" + "---|" * 9]
        for c in cands_p:
            for mode in ("beam_search", "incoherent"):
                out.append(f"| {c} | {mode} | " + " | ".join(
                    cell(gi.get((sc, c, mode, b, 1.0, cls, 1e-3, 0.5))) for sc in ("N-AMB", "N-FLOW", "N-SENS")
                    for b in ("B1", "B2", "B3")) + " |")
        out.append("")

    out += ["## Secondary candidates, N-AMB, T = 1 s, beam_search", "",
            "| Candidate | " + " | ".join(f"{cls} {b}" for cls in CLASSES for b in ("B1", "B2", "B3")) + " |",
            "|---|" + "---|" * 12]
    for c in cands_s + ["P8-C"]:
        out.append(f"| {c} | " + " | ".join(cell(gi.get(("N-AMB", c, "beam_search", b, 1.0, cls, 1e-3, 0.5)))
                                            for cls in CLASSES for b in ("B1", "B2", "B3")) + " |")
    out.append("")

    out += ["## 60 s coherent tonal, B1, N-AMB", "", "| Candidate | beam_known | beam_search | incoherent |",
            "|---|---|---|---|"]
    for c in cands_p:
        out.append(f"| {c} | " + " | ".join(cell(gi.get(("N-AMB", c, m, "B1", 60.0, "tone", 1e-3, 0.5)))
                                            for m in MODES) + " |")
    out.append("")

    # false-alarm calibration (matched)
    out += ["## False-alarm calibration, matched noise (evaluation sets)", "",
            "| Method | Target Pfa | Rows | Realized Pfa range | Rows whose 95 % interval excludes the target |",
            "|---|---|---|---|---|"]
    prim = [r for r in thr if r["kind"] == "primary"]
    for meth in ("exact", "empirical", "bound"):
        for p in (0.01, 0.001, 0.0001):
            rr = [r for r in prim if r["method"] == meth and f(r["pfa_target"]) == p]
            if not rr:
                continue
            vals = [f(r["realized_pfa"]) for r in rr]
            miss = sum(1 for r in rr if not f(r["realized_lo"]) <= p <= f(r["realized_hi"]))
            out.append(f"| {meth} | {p:g} | {len(rr)} | {min(vals):.4f} to {max(vals):.4f} | {miss} |")
    nest = defaultdict(int)
    for r in prim:
        if r["method"] == "not estimated":
            nest[(r["mode"], f(r["pfa_target"]))] += 1
    out += ["", "Thresholds not estimated (no exact law, too few calibration trials, no bound): " +
            (", ".join(f"{m} at {p:g}: {n}" for (m, p), n in sorted(nest.items())) or "none") + ".", ""]

    # bound conservatism
    out += ["## Union-bound conservatism (bound thresholds evaluated on evaluation sets, n x Pfa >= 10)", "",
            "| Mode | Detector | Rows | Largest realized Pfa / target | Median realized Pfa / target |",
            "|---|---|---|---|---|"]
    bc = defaultdict(list)
    for r in prim:
        if math.isfinite(f(r["bound_eta"])) and f(r["n_eval"]) * f(r["pfa_target"]) >= 10:
            bc[(r["mode"], r["detector"])].append(f(r["bound_realized_pfa"]) / f(r["pfa_target"]))
    for (m, d), v in sorted(bc.items()):
        v = sorted(v)
        out.append(f"| {m} | {d} | {len(v)} | {max(v):.3f} | {v[len(v) // 2]:.3f} |")
    out.append("")

    # mismatch
    out += ["## Mismatched noise assumptions: realized Pfa (target 0.01 / 0.001), T = 1 s", "",
            "| Experiment | Band | Candidate | Mode | tonal | harmonic | energy | mf |", "|---|---|---|---|---|---|---|---|"]
    mm = [r for r in thr if r["kind"] == "mismatch"]
    keys = sorted({(r["experiment"], r["band"], r["candidate"], r["mode"]) for r in mm})
    for k in keys:
        cells = []
        for d in ("tonal", "harmonic", "energy", "mf"):
            v = []
            for p in (0.01, 0.001):
                rr = [r for r in mm if (r["experiment"], r["band"], r["candidate"], r["mode"]) == k
                      and r["detector"] == d and f(r["pfa_target"]) == p]
                v.append(f"{f(rr[0]['realized_pfa']):.3g}" if rr and math.isfinite(f(rr[0]["eta"])) else "n/a")
            cells.append(" / ".join(v))
        out.append(f"| {k[0]} | {k[1]} | {k[2]} | {k[3]} | " + " | ".join(cells) + " |")
    out.append("")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1]))
